-- ============================================================================
-- NameSync — target schema for the `lakeshore` Postgres schema (onewebdb)
-- ============================================================================
-- Clean cutover: no data to preserve. Drops the GraphML-draft tables and
-- creates the redesign. Every object is schema-qualified (lakeshore.*) so it
-- never depends on the session search_path.
--
-- Model: append-only ("stacking"). Every uploaded row is stored as-is, tagged
-- with the upload that added it (upload_id FK). Uploads are immutable snapshots;
-- no cross-upload dedup, so a rollback is simply "delete this upload's rows".
--   * comparison / comparison_result split the run (header) from its scored
--     matches (rows) — the header is the durable home for status + expected_batches.
--
-- Keys: bigint identity (matches the existing batch_file.id bigserial / int8 style).
-- Types: timestamptz, jsonb, text+CHECK "enums".
-- ============================================================================

