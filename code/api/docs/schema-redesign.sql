-- ─────────────────────────────────────────────────────────────
-- upload: one import event (a single company CSV OR a single social JSON).
-- Roll-back-able. (Replaces upload_record + batch_file.)
-- ─────────────────────────────────────────────────────────────
CREATE TABLE lakeshore.upload (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              varchar(255),
  kind              text NOT NULL CHECK (kind IN ('company','social')),
  source            varchar(100),                            -- social: 'facebook'|'linkedin'|…; company: NULL
  status            text NOT NULL DEFAULT 'processing'
                      CHECK (status IN ('pending','processing','pending_webhook',
                                        'completed','failed','rolled_back')),
  mode              varchar(20),                             -- known values: 'fresh' | 'continue'
  uploaded_by       varchar(255),
  total_records     integer NOT NULL DEFAULT 0,             -- rows this import added
  duplicate_records integer NOT NULL DEFAULT 0,             -- informational (0 under stacking)
  -- The run this import started (EXTERNAL_MATCHER only; NULL otherwise — an import made with
  -- the internal matcher starts no run). The foreign key is added further down, once
  -- `comparison` exists: this table is declared before it.
  comparison_id     bigint,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_upload_created ON lakeshore.upload (created_at DESC);
CREATE INDEX idx_upload_kind    ON lakeshore.upload (kind);
CREATE INDEX idx_upload_status  ON lakeshore.upload (status);


-- ─────────────────────────────────────────────────────────────
-- friend: social contacts, one row per uploaded line (append-only). Belongs to
-- exactly one upload; rolling back that upload deletes its rows (ON DELETE CASCADE).
-- ─────────────────────────────────────────────────────────────
-- The `*_clean` columns hold the name with titles, suffixes, nicknames and middle tokens
-- stripped (api/src/services/name-cleaner.service.ts), written at import next to — never
-- over — the raw name. Matching, dedup and display read clean; the raw column is the
-- record of what the file actually said, so a bad rule is a backfill, not a re-upload.
CREATE TABLE lakeshore.friend (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  upload_id         bigint NOT NULL REFERENCES lakeshore.upload(id) ON DELETE CASCADE,
  source            varchar(100) NOT NULL,                  -- 'facebook' | 'linkedin' | …
  friend_name       varchar(255),                           -- as uploaded
  friend_name_clean varchar(255),                           -- derived; NULL only if raw is
  source_timestamp  timestamptz,
  fetched           boolean NOT NULL DEFAULT false,         -- through a completed comparison ("old")
  -- The external workflow's verdict on this row: 'processing' → 'match' | 'unmatch'.
  -- No CHECK on purpose: an unexpected value must not fail the workflow's write, and the
  -- app reads anything other than 'processing' as "finished". See docs/EXTERNAL-MATCHER.md.
  status            text NOT NULL DEFAULT 'processing',
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_friend_upload     ON lakeshore.friend (upload_id);       -- rollback / by-upload
CREATE INDEX idx_friend_name       ON lakeshore.friend (friend_name);     -- results lookup
CREATE INDEX idx_friend_name_clean ON lakeshore.friend (friend_name_clean); -- matcher + dedup
CREATE INDEX idx_friend_fetched    ON lakeshore.friend (fetched);         -- stats
-- "Is this upload still working?" — the poll that decides an import is done.
CREATE INDEX idx_friend_upload_status ON lakeshore.friend (upload_id, status);


-- ─────────────────────────────────────────────────────────────
-- company_contact: company people, append-only, one upload per row.
-- ─────────────────────────────────────────────────────────────
-- Same raw/clean pair as `friend`, once per script. company_name has no clean twin: it is
-- only ever grouped and matched exactly, and "Mr" inside a company's name is its name.
CREATE TABLE lakeshore.company_contact (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  upload_id            bigint NOT NULL REFERENCES lakeshore.upload(id) ON DELETE CASCADE,
  company_name         varchar(255),
  person_name_th       varchar(255),                        -- as uploaded
  person_name_th_clean varchar(255),                        -- derived; NULL only if raw is
  person_name_en       varchar(255),                        -- as uploaded
  person_name_en_clean varchar(255),                        -- derived; NULL only if raw is
  fetched              boolean NOT NULL DEFAULT false,
  -- Same as friend.status — the workflow's verdict on this row.
  status               text NOT NULL DEFAULT 'processing',
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_company_contact_upload  ON lakeshore.company_contact (upload_id);
CREATE INDEX idx_company_contact_company ON lakeshore.company_contact (company_name);
CREATE INDEX idx_company_contact_fetched ON lakeshore.company_contact (fetched);
CREATE INDEX idx_company_contact_upload_status ON lakeshore.company_contact (upload_id, status);
-- The matcher reads (company_name → both clean names) for every compare run.
CREATE INDEX idx_company_contact_clean   ON lakeshore.company_contact (company_name, person_name_th_clean, person_name_en_clean);


-- ─────────────────────────────────────────────────────────────
-- comparison: one compare run (the header). selected_company is what the run
-- matched against; expected_batches is the durable denominator for progress.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE lakeshore.comparison (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             varchar(255),
  selected_company varchar(255),
  source           varchar(100),                            -- social source compared
  status           text NOT NULL DEFAULT 'processing'
                     CHECK (status IN ('pending','processing','completed','failed')),
  expected_batches integer,                                 -- total declared by the matcher (0/NULL = unknown)
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_comparison_created ON lakeshore.comparison (created_at DESC);

-- comparison_result: the scored matches, appended one batch at a time.
CREATE TABLE lakeshore.comparison_result (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comparison_id  bigint NOT NULL REFERENCES lakeshore.comparison(id) ON DELETE CASCADE,
  friend_name    varchar(255),
  person_name_en varchar(255),
  person_name_th varchar(255),
  matching_score real,
  batch_number   integer,
  is_complete    boolean NOT NULL DEFAULT false,
  upload_name    varchar(255),                              -- connected uploader, when matcher provides it
  extra          jsonb,                                     -- non-standard matcher fields
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_comparison_result_comparison ON lakeshore.comparison_result (comparison_id);
-- Serves both the distinct-batch progress count and batch-level idempotency.
CREATE INDEX idx_comparison_result_batch ON lakeshore.comparison_result (comparison_id, batch_number);

-- upload.comparison_id → comparison. Declared here rather than on the column, because
-- `upload` is created before `comparison` is.
ALTER TABLE lakeshore.upload
  ADD CONSTRAINT upload_comparison_id_fkey
  FOREIGN KEY (comparison_id) REFERENCES lakeshore.comparison(id) ON DELETE SET NULL;


