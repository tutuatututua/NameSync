-- ─────────────────────────────────────────────────────────────
-- saved_query: a named, re-runnable query from the Database console.
--   kind='sql'      sql_text holds a read-only SELECT typed into the SQL editor
--   kind='builder'  spec holds the visual builder's {table, filters, sort} as JSON
-- created_by is the app_user id of whoever saved it.
-- (Mirrored by migrations/0014_create_saved_query.ts — keep the two in step.)
-- ─────────────────────────────────────────────────────────────
CREATE TABLE lakeshore.saved_query (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       varchar(255) NOT NULL,
  kind       text NOT NULL CHECK (kind IN ('sql','builder')),
  sql_text   text,
  spec       jsonb,
  created_by varchar(255),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_saved_query_created ON lakeshore.saved_query (created_at DESC);


-- ─────────────────────────────────────────────────────────────
-- app_user / auth_session: authentication.
--
-- NameSync used to sit behind a website that logged the user in and handed over a JWT —
-- it only ever *verified* one. It now owns the whole flow, which is what these two tables
-- are for. password_hash is a self-describing scrypt string (api/src/lib/password.ts);
-- token_hash is the SHA-256 of the session token the browser holds, so a dump of
-- auth_session yields nothing that can be replayed as a login.
--
-- A session is a ROW, which is the point: it can be revoked. A JWT cannot be.
-- (Mirrored by migrations/0015_create_auth_tables.ts — keep the two in step.)
-- ─────────────────────────────────────────────────────────────
CREATE TABLE lakeshore.app_user (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         varchar(320) NOT NULL,        -- 64 local + @ + 255 domain
  password_hash text NOT NULL,
  name          varchar(255),
  roles         text[] NOT NULL DEFAULT '{}',
  is_active     boolean NOT NULL DEFAULT true,
  last_login_at timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
-- On lower(email), not email: otherwise Ann@x.com and ann@x.com are two accounts, and
-- which one you get at login depends on how you typed it.
CREATE UNIQUE INDEX idx_app_user_email ON lakeshore.app_user (lower(email));

CREATE TABLE lakeshore.auth_session (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Deleting a user must take their live sessions with them, or they stay signed in.
  user_id      bigint NOT NULL REFERENCES lakeshore.app_user (id) ON DELETE CASCADE,
  token_hash   varchar(64) NOT NULL UNIQUE,   -- sha256 hex of the token the browser holds
  expires_at   timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  user_agent   text,
  ip           varchar(64),
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_auth_session_user    ON lakeshore.auth_session (user_id);     -- "sign out everywhere"
CREATE INDEX idx_auth_session_expires ON lakeshore.auth_session (expires_at);  -- sweep of expired rows


-- ============================================================================
-- Optional: keep updated_at fresh (Postgres has no built-in "on update").
-- Uses EXECUTE PROCEDURE (not EXECUTE FUNCTION) so it works on Postgres 10;
-- PROCEDURE is still accepted on every newer version too.
-- ============================================================================
CREATE OR REPLACE FUNCTION lakeshore.set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_upload_updated          ON lakeshore.upload;
CREATE TRIGGER trg_upload_updated          BEFORE UPDATE ON lakeshore.upload
  FOR EACH ROW EXECUTE PROCEDURE lakeshore.set_updated_at();
DROP TRIGGER IF EXISTS trg_friend_updated          ON lakeshore.friend;
CREATE TRIGGER trg_friend_updated          BEFORE UPDATE ON lakeshore.friend
  FOR EACH ROW EXECUTE PROCEDURE lakeshore.set_updated_at();
DROP TRIGGER IF EXISTS trg_company_contact_updated ON lakeshore.company_contact;
CREATE TRIGGER trg_company_contact_updated BEFORE UPDATE ON lakeshore.company_contact
  FOR EACH ROW EXECUTE PROCEDURE lakeshore.set_updated_at();
DROP TRIGGER IF EXISTS trg_comparison_updated      ON lakeshore.comparison;
CREATE TRIGGER trg_comparison_updated      BEFORE UPDATE ON lakeshore.comparison
  FOR EACH ROW EXECUTE PROCEDURE lakeshore.set_updated_at();
DROP TRIGGER IF EXISTS trg_saved_query_updated     ON lakeshore.saved_query;
CREATE TRIGGER trg_saved_query_updated     BEFORE UPDATE ON lakeshore.saved_query
  FOR EACH ROW EXECUTE PROCEDURE lakeshore.set_updated_at();
DROP TRIGGER IF EXISTS trg_app_user_updated        ON lakeshore.app_user;
CREATE TRIGGER trg_app_user_updated        BEFORE UPDATE ON lakeshore.app_user
  FOR EACH ROW EXECUTE PROCEDURE lakeshore.set_updated_at();


